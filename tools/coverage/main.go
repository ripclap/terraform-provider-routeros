// Writes COVERAGE.md: which resources this fork registers that upstream does not.
//
// The comparison is against a committed list of upstream's resource names rather
// than against upstream itself, so it needs no network access and does not change
// underfoot when upstream releases.
//
//	go run tools/coverage/main.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/ripclap/terraform-provider-routeros/routeros"
)

const (
	baselineFile = "tools/coverage/upstream-v1.99.1.txt"
	baselineName = "v1.99.1"
	outputFile   = "COVERAGE.md"
)

// Groups resources into the sections of the document. Order is the order they
// appear; the first prefix that matches wins, so put the specific ones first.
var sections = []struct {
	title  string
	prefix []string
}{
	{"Routing", []string{"routeros_routing_"}},
	{"MPLS", []string{"routeros_mpls_"}},
	{"Bridging and switching", []string{"routeros_interface_bridge", "routeros_bridge", "routeros_interface_ethernet_switch"}},
	{"Interfaces and tunnels", []string{"routeros_interface_"}},
	{"IPv6", []string{"routeros_ipv6_"}},
	{"IPv4", []string{"routeros_ip_"}},
	{"System", []string{"routeros_system_", "routeros_console_", "routeros_partitions", "routeros_disk", "routeros_port", "routeros_special_", "routeros_file_", "routeros_certificate_"}},
	{"Tools and services", []string{"routeros_tool_", "routeros_app", "routeros_queue_", "routeros_ppp_", "routeros_user_", "routeros_zerotier", "routeros_openflow", "routeros_iot_"}},
}

func readBaseline(path string) (map[string]bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	out := map[string]bool{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		out[line] = true
	}
	return out, sc.Err()
}

func section(name string) string {
	for _, s := range sections {
		for _, p := range s.prefix {
			if strings.HasPrefix(name, p) {
				return s.title
			}
		}
	}
	return "Other"
}

func main() {
	upstream, err := readBaseline(baselineFile)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	p := routeros.Provider()
	paths := map[string]string{}
	var added, missing []string
	for name, res := range p.ResourcesMap {
		if f, ok := res.Schema[routeros.MetaResourcePath]; ok && f.Default != nil {
			paths[name], _ = f.Default.(string)
		}
		if !upstream[name] {
			added = append(added, name)
		}
	}
	for name := range upstream {
		if _, ok := p.ResourcesMap[name]; !ok {
			missing = append(missing, name)
		}
	}
	sort.Strings(added)
	sort.Strings(missing)

	menus := map[string]bool{}
	for _, path := range paths {
		if strings.HasPrefix(path, "/") {
			menus[path] = true
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Coverage\n\n")
	fmt.Fprintf(&b, "Generated by `go run tools/coverage/main.go`; do not edit.\n\n")
	fmt.Fprintf(&b, "Compared against upstream %s.\n\n", baselineName)
	fmt.Fprintf(&b, "| | upstream %s | this fork |\n|---|--:|--:|\n", baselineName)
	fmt.Fprintf(&b, "| Registered resources | %d | **%d** |\n", len(upstream), len(p.ResourcesMap))
	fmt.Fprintf(&b, "| Distinct RouterOS menus | - | **%d** |\n\n", len(menus))

	if len(missing) == 0 {
		fmt.Fprintf(&b, "Every resource upstream registers is also registered here.\n\n")
	} else {
		fmt.Fprintf(&b, "Registered upstream but not here: %s.\n\n", strings.Join(missing, ", "))
	}

	fmt.Fprintf(&b, "## Resources added by this fork (%d)\n", len(added))

	grouped := map[string][]string{}
	for _, name := range added {
		grouped[section(name)] = append(grouped[section(name)], name)
	}
	order := make([]string, 0, len(sections)+1)
	for _, s := range sections {
		order = append(order, s.title)
	}
	order = append(order, "Other")

	for _, title := range order {
		list := grouped[title]
		if len(list) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n### %s (%d)\n\n", title, len(list))
		fmt.Fprintf(&b, "| resource | RouterOS menu |\n|---|---|\n")
		for _, name := range list {
			fmt.Fprintf(&b, "| `%s` | `%s` |\n", name, paths[name])
		}
	}

	if err := os.WriteFile(outputFile, []byte(b.String()), 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("%s: %d added, %d missing, %d menus\n", outputFile, len(added), len(missing), len(menus))
}

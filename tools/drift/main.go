package main

import (
	"bytes"
	"go/format"
	"log"
	"os"
	"text/template"

	"gopkg.in/yaml.v3"
)

type YamlROS map[string]map[string][]struct {
	TF string
	MT string
}

func main() {
	m := YamlROS{}
	fileIn, err := os.Open("mikrotik_resource_drift.yaml")
	if err != nil {
		log.Fatalf("error: %v", err)
	}
	defer fileIn.Close()

	dec := yaml.NewDecoder(fileIn)
	if err := dec.Decode(&m); err != nil {
		log.Fatalf("error: %v", err)
	}

	var buf bytes.Buffer
	if err := driftTemplate.Execute(&buf, m); err != nil {
		log.Fatalf("error: %v", err)
	}

	// The result is committed, so it has to be gofmt'd; formatting it here keeps
	// the template from having to produce well indented output on its own.
	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("error: %v", err)
	}

	if err := os.WriteFile("mikrotik_resource_drift.go", out, 0644); err != nil {
		log.Fatalf("error: %v", err)
	}
}

var driftTemplate = template.Must(template.New("").Parse(`// Code generated by "tools/drift/main.go"; DO NOT EDIT.
package routeros

func init() {
{{- range $version, $resource := . }}
  {{- range $name, $attributes := $resource }}
    {{- range $attr := $attributes }}
    {{ printf "driftAttributeSlice.Add(%q, %q, %q, %q)" $version $name $attr.TF $attr.MT }}
    {{- end }}
  {{- end }}
{{- end }}
    driftAttributeSlice.SortDesc()
}
`))
